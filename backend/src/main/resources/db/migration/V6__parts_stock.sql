-- Parts kept in stock. on_hand may go below zero: a customer's approval is never refused for
-- want of stock, and a negative count is the number of parts still to order.
create table part (
  id bigint generated by default as identity primary key,
  version bigint not null,
  sku varchar(30) not null unique,
  name varchar(200) not null,
  unit_price_sen bigint not null check (unit_price_sen >= 0),
  on_hand integer not null,
  reorder_level integer not null check (reorder_level >= 0)
);

-- A quote line may say which stock part it uses. Old lines use none.
alter table quote_line add column part_id bigint references part (id);

-- Every change to a part's count, newest last. Taken lines keep the job they were taken for.
create table stock_movement (
  id bigint generated by default as identity primary key,
  part_id bigint not null references part (id),
  job_card_id bigint references job_card (id) on delete set null,
  quantity_change integer not null check (quantity_change <> 0),
  reason varchar(20) not null,
  occurred_at timestamp with time zone not null,
  by_name varchar(100)
);
create index stock_movement_part on stock_movement (part_id, id);
create index stock_movement_job on stock_movement (job_card_id);
