create table customer (
  id bigint generated by default as identity primary key,
  name varchar(100) not null,
  phone varchar(20) not null
);

create table vehicle (
  id bigint generated by default as identity primary key,
  plate varchar(16) not null unique,
  make varchar(40) not null,
  model varchar(40) not null,
  model_year integer,
  customer_id bigint not null references customer (id)
);

create table job_card (
  id bigint generated by default as identity primary key,
  version bigint not null,
  vehicle_id bigint not null references vehicle (id),
  complaint varchar(1000) not null,
  mileage_km integer,
  status varchar(20) not null,
  quote_version integer not null,
  public_token varchar(32) not null unique,
  created_at timestamp with time zone not null
);

create index job_card_status on job_card (status);
create index job_card_vehicle on job_card (vehicle_id);

create table quote_line (
  id bigint generated by default as identity primary key,
  job_card_id bigint not null references job_card (id) on delete cascade,
  kind varchar(10) not null,
  description varchar(200) not null,
  quantity integer not null check (quantity > 0),
  unit_price_sen bigint not null check (unit_price_sen >= 0),
  taxable boolean not null
);

create table status_event (
  id bigint generated by default as identity primary key,
  job_card_id bigint not null references job_card (id) on delete cascade,
  from_status varchar(20),
  to_status varchar(20) not null,
  occurred_at timestamp with time zone not null,
  note varchar(500)
);
