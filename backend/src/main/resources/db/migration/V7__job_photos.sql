-- Before/after photos of a job. Kept in the database (no files on disk, so no file paths to get
-- wrong): every photo is decoded and re-encoded as a JPEG of at most 1600 px on the long side
-- before it is stored, which also drops camera metadata such as GPS position.
create table job_photo (
  id bigint generated by default as identity primary key,
  job_card_id bigint not null references job_card (id) on delete cascade,
  -- For the customer's link: random, so the link does not show internal ids.
  public_key varchar(16) not null unique,
  stage varchar(10) not null,
  width integer not null check (width > 0),
  height integer not null check (height > 0),
  size_bytes integer not null check (size_bytes > 0),
  data bytea not null,
  caption varchar(200),
  created_at timestamp with time zone not null,
  by_name varchar(100) not null
);
create index job_photo_job on job_photo (job_card_id, id);
